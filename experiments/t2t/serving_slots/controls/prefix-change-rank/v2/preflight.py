def shapes():
    # Partial prompt, an uninitialized candidate, a dirty row and a masked row.
    def call(base, expected_pool, expected_rows, slack, *, quota=2, frontier=10):
        m=np.ones(32,dtype=np.uint8)
        m[7]=0
        extra, pool, spare=plan_prefix_refresh(prompt_len=67,block_start=64,
            cached_prefix_before=frontier,old_mask=m,dirty={69},initialized=set(range(64,96))-{70},
            original_positions=base,offer=8,quota=quota)
        for a,vals in [(extra,expected_rows),(pool,expected_pool)]:
            need(a.dtype==np.int64 and a.shape==(len(vals),) and a.tolist()==vals,"shape or IDs")
        need(spare==slack,"wrong slack")
        return [len(base),pool.size,extra.size,spare]
    # Independent expectations, not generated by either side of the tape comparison.
    valid=[67,68,72,73]
    return [call(list(range(76,84)),[],[],0),
            call(list(range(76,83)),valid,[73],1),
            call(list(range(76,81)),valid,[72,73],3),
            call([76,77],[],[],6,frontier=3),
            call([76,77],[],[],0,quota=0)]


def stop_oracle(h):
    # The sealed stock inputs recover each frozen row's *paid* ID; never use a draft
    # or a future input to decide the stopping tick. The later input only checks
    # the ID on an owed terminal payment, after the stop has been identified.
    path=ROOT/"runtime/llada-ibs-certified-eos-h0-v1/tools/llada_ibs_eos_stop.py"
    need(filehash(path)=="70f58f50cf3ba3fa8515b7b81a92d92ea4b97fa964e3516686ccd5064627889b","stop source")
    spec=importlib.util.spec_from_file_location("original_paid_stop",path)
    mod=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    paid={}
    for j,(e,ids) in enumerate(zip(h["events"],h["forward_inputs"],strict=True)):
        paid.update(zip(e["absolute_positions"],ids,strict=True))
        if e["phase"]=="prefill":
            continue
        start=32*e["block"]
        due=e["written_absolute"]
        need(not any(a<start+e["cached_prefix_after"] for a in due),"dirty frozen prefix")
        pos=mod.frozen_eos(lambda l,u:[paid[a] for a in range(l,u)],prompt=len(h["prompt_ids"]),
            cap=h["generation_cap"],start=start,ready=e["cached_prefix_after"],eos={156892})
        if pos is not None:
            need(all(a in paid and start+e["cached_prefix_after"]<=a<start+32 for a in due)
                 and len(due)<=8,"debt shape")
            return dict(event=j,eos=pos,due=sorted(due))
    return None


def check():
    need(os.environ.get("CUDA_VISIBLE_DEVICES")=="","disable CUDA for preflight")
    shape=shapes()
    reg=read(D/"registration.json")
    runs=DATA/reg["history"]
    run=read(runs/"run.json")
    exposure=replay()
    sealed=(json.dumps(exposure,sort_keys=True,separators=(",",":"))+"\n").encode()
    need(sealed==(PRIOR/"exposure.json").read_bytes()==(D/"exposure.json").read_bytes() and
         filehash(D/"exposure.json")=="cb055ecf2e83bc37be931b630d6b01a94dc845d7670ccf105997eefbcd9612a2","old gate")
    for rec in exposure["records"]:
        label=run["arms"]["0" if rec["arm"]=="none" else "2"]
        hist=read(runs/f"{rec['index']:02}-{label}.json")
        need(stop_oracle(hist)==rec["certificate"],"pinned stock-stop witness")
    need(RETAINED_SHA==filehash(RETAINED),"prior bytes")
    raw=read(RETAINED)
    h=read(runs/f"07-{run['arms']['0']}.json")
    r,tape=raw["row"],raw["tape"]
    need(raw["registration"]==exposure["registration"] and raw["arm"]=="none" and
         all(r[k]==h[k] for k in ("index","task_id","seed","dataset","prompt_ids","generation_cap")),"wrong input")
    facts,_=audit(r,"none",live=True,tape=tape)
    cert=stop_oracle(h)
    need(cert==facts["certificate"] and r["generation_physical_padded_rows"]==r["generation_query_rows"]
         and sum(c["physical_rows"] for c in r["calls"])==r["prefill_rows"]+r["generation_query_rows"],
         "original paid-stop or physical bill")
    verify_mask(raw["masks"],r)
    control_ref(r,h,cert)
    t=next(t for t in tape if t["plan"]["right"]!=t["plan"]["change"])
    for corrupt in ("tick","pool","scores","mask"):
        bad=copy.deepcopy(tape)
        b=bad[t["tick"]]
        if corrupt=="tick": b["tick"]+=1
        if corrupt=="pool": b["plan"]["candidates"].pop()
        if corrupt=="scores": b["plan"]["scores"].clear()
        if corrupt=="mask": b["mask"][0]=not b["mask"][0]
        try: audit(r,"none",live=True,tape=bad)
        except ValueError as exc: need(str(exc)=="live version/role tape","unexpected rejection")
        else: raise AssertionError("corruption accepted")
    ts=tape[2]
    need(len(ts["paid"])==8 and ts["plan"]==dict(right=[],change=[],scores={},candidates=[]),"first mismatch")
    return dict(passed=True,no_model=True,same_raw_sha=RETAINED_SHA,helper_shapes=shape,
        pinned_stop_historical_trajectories=len(exposure["records"]),exposure_sha=filehash(D/"exposure.json"),
        first_v1_mismatch=dict(tick=2,paid=len(ts["paid"]),slack=0,conceptual=3,enumerated=0,picks=0),
        positive_corruptions_rejected=4,positive_test_tick=t["tick"],certificate=cert,
        N=r["output_tokens"],F=r["generation_forwards"],Q=r["generation_query_rows"],
        prefill_Q=r["prefill_rows"],projection_layers=r["verified_layers"],ids_sha=digest(r["output_ids"]),
        raw_calls=len(r["calls"]),ordinary=facts["counts"])


if __name__=="__main__":
    print(json.dumps(check(),sort_keys=True))
